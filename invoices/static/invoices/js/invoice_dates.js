(function () {
  const SCRIPT_IDS = {
    paymentTerms: 'payment-terms-meta',
    projects: 'project-payment-config',
    customers: 'customer-payment-config',
  };

  const store = {
    paymentTerms: {},
    projects: {},
    customers: {},
  };

  function toMap(list) {
    const map = {};
    if (!Array.isArray(list)) {
      return map;
    }
    list.forEach((item) => {
      if (!item || item.id === undefined || item.id === null) {
        return;
      }
      map[String(item.id)] = item;
    });
    return map;
  }

  function parseScript(id) {
    const el = document.getElementById(id);
    if (!el) {
      return null;
    }
    try {
      return JSON.parse(el.textContent);
    } catch (error) {
      return null;
    } finally {
      el.remove();
    }
  }

  function mergeStore(target, source) {
    if (!source) {
      return;
    }
    Object.keys(source).forEach((key) => {
      target[key] = source[key];
    });
  }

  function ensureData() {
    const existing = window.__invoicePaymentData;
    if (existing) {
      mergeStore(store.paymentTerms, existing.paymentTerms || {});
      mergeStore(store.projects, existing.projects || {});
      mergeStore(store.customers, existing.customers || {});
    }

    const paymentTerms = toMap(parseScript(SCRIPT_IDS.paymentTerms));
    const projects = toMap(parseScript(SCRIPT_IDS.projects));
    const customers = toMap(parseScript(SCRIPT_IDS.customers));

    mergeStore(store.paymentTerms, paymentTerms);
    mergeStore(store.projects, projects);
    mergeStore(store.customers, customers);

    window.__invoicePaymentData = {
      paymentTerms: store.paymentTerms,
      projects: store.projects,
      customers: store.customers,
    };
  }

  function daysForTerm(termId) {
    if (!termId) {
      return null;
    }
    const term = store.paymentTerms[String(termId)];
    if (!term) {
      return null;
    }
    return Number(term.days) || 0;
  }

  function defaultTermForProject(projectId) {
    if (!projectId) {
      return null;
    }
    const project = store.projects[String(projectId)];
    if (!project) {
      return null;
    }
    if (project.payment_term) {
      return String(project.payment_term);
    }
    if (project.customer_payment_term) {
      return String(project.customer_payment_term);
    }
    return null;
  }

  function parseDate(value) {
    if (!value) {
      return null;
    }
    const [year, month, day] = value.split('-').map(Number);
    if (!year || !month || !day) {
      return null;
    }
    const date = new Date(Date.UTC(year, month - 1, day));
    if (Number.isNaN(date.getTime())) {
      return null;
    }
    return date;
  }

  function formatDate(date) {
    const year = date.getUTCFullYear();
    const month = String(date.getUTCMonth() + 1).padStart(2, '0');
    const day = String(date.getUTCDate()).padStart(2, '0');
    return `${year}-${month}-${day}`;
  }

  function initForm(form) {
    if (!form || form.dataset.invoiceDatesInitialised) {
      return;
    }
    form.dataset.invoiceDatesInitialised = 'true';

    const paymentSelect = form.querySelector('[name$="payment_term"]');
    const issuedInput = form.querySelector('[name$="issued_date"]');
    const dueInput = form.querySelector('[name$="due_date"]');
    const projectSelect = form.querySelector('[name$="project"]');
    const bankAccountSelect = form.querySelector('[name$="bank_account"]');

    if (!paymentSelect && !dueInput) {
      return;
    }

    let manualDue = dueInput && dueInput.value ? true : false;
    let manualBankAccount = false;

    function updateDueDate() {
      if (!dueInput) {
        return;
      }
      const termId = paymentSelect && paymentSelect.value ? paymentSelect.value : null;
      const issuedDate = issuedInput ? issuedInput.value : null;
      if (!termId || !issuedDate) {
        dueInput.value = '';
        manualDue = false;
        const clearedEvent = new Event('change', { bubbles: true });
        clearedEvent.autoGenerated = true;
        dueInput.dispatchEvent(clearedEvent);
        return;
      }
      const days = daysForTerm(termId);
      const baseDate = parseDate(issuedDate);
      if (days == null || !baseDate) {
        return;
      }
      const computed = new Date(baseDate.getTime());
      computed.setUTCDate(computed.getUTCDate() + days);
      dueInput.value = formatDate(computed);
      manualDue = false;
      const changeEvent = new Event('change', { bubbles: true });
      changeEvent.autoGenerated = true;
      dueInput.dispatchEvent(changeEvent);
    }

    function applyProjectDefaults() {
      if (!projectSelect) {
        return;
      }
      const projectId = projectSelect.value;
      if (!projectId) {
        return;
      }
      const project = store.projects[String(projectId)] || {};
      const suggested = defaultTermForProject(projectId);
      if (paymentSelect) {
        if (suggested) {
          if (paymentSelect.value !== suggested) {
            paymentSelect.value = suggested;
            manualDue = false;
            paymentSelect.dispatchEvent(new Event('change', { bubbles: true }));
          } else if (!manualDue) {
            updateDueDate();
          }
        } else if (paymentSelect.value) {
          paymentSelect.value = '';
          manualDue = false;
          paymentSelect.dispatchEvent(new Event('change', { bubbles: true }));
        } else if (!manualDue) {
          updateDueDate();
        }
      }
      if (bankAccountSelect && !manualBankAccount && project.bank_account) {
        const suggestedAccount = String(project.bank_account);
        if (bankAccountSelect.value !== suggestedAccount) {
          bankAccountSelect.value = suggestedAccount;
          bankAccountSelect.dispatchEvent(new Event('change', { bubbles: true }));
        }
      }
    }

    if (projectSelect) {
      projectSelect.addEventListener('change', () => {
        manualDue = false;
        manualBankAccount = false;
        applyProjectDefaults();
      });
    }

    if (bankAccountSelect) {
      bankAccountSelect.addEventListener('change', () => {
        manualBankAccount = true;
      });
    }

    if (paymentSelect) {
      paymentSelect.addEventListener('change', () => {
        manualDue = false;
        updateDueDate();
      });
    }

    if (issuedInput) {
      issuedInput.addEventListener('change', () => {
        manualDue = false;
        updateDueDate();
      });
    }

    if (dueInput) {
      const markManual = (event) => {
        if (event && event.autoGenerated) {
          return;
        }
        manualDue = true;
      };
      dueInput.addEventListener('input', markManual);
      dueInput.addEventListener('change', markManual);
    }

    const hasExistingDue = Boolean(dueInput && dueInput.value);
    if (projectSelect && projectSelect.value) {
      if (!hasExistingDue) {
        applyProjectDefaults();
      }
    } else if (!hasExistingDue && paymentSelect && paymentSelect.value) {
      updateDueDate();
    }
  }

  function initAll() {
    ensureData();
    document.querySelectorAll('[data-invoice-dates]').forEach((form) => initForm(form));
  }

  function initFrom(element) {
    ensureData();
    if (!element) {
      return;
    }
    if (element.matches && element.matches('[data-invoice-dates]')) {
      initForm(element);
      return;
    }
    element.querySelectorAll('[data-invoice-dates]').forEach((form) => initForm(form));
  }

  window.invoiceDates = window.invoiceDates || {};
  window.invoiceDates.init = initFrom;

  document.addEventListener('DOMContentLoaded', initAll);
})();
